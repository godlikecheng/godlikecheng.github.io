/* 布置出生区与基地（genMap 与 loadClassic 共用） */
function setupSpawnsAndBase() {
  const clear = (cx, cy) => {
    for (let y = cy; y < cy + 4; y++) for (let x = cx; x < cx + 4; x++)
      if (map[y] && map[y][x] !== undefined) map[y][x] = T_EMPTY;
  };
  clear(0, 0); clear(11, 0); clear(22, 0);          // 敌方出生区
  clear(7, 22); clear(15, 22);                       // 玩家 P1 / P2 出生区
  // 基地 + 砖墙护卫
  map[24][12] = T_BASE; map[24][13] = T_BASE; map[25][12] = T_BASE; map[25][13] = T_BASE;
  [[11,23],[12,23],[13,23],[14,23],[11,24],[14,24],[11,25],[14,25]].forEach(([x,y]) => map[y][x] = T_BRICK);
  clear(7, 22); clear(15, 22);                       // 再清一次保证玩家出生点
}

/* 字符 → 地形类型 */
function charToTerrain(ch) {
  return ch === "#" ? T_BRICK : ch === "@" ? T_STEEL : ch === "~" ? T_WATER
       : ch === "%" ? T_TREE : ch === "i" ? T_ICE : T_EMPTY;
}

/* 加载经典关卡（第 n 关，n 从 1 开始） */
function loadClassic(n) {
  map = Array.from({length: ROWS}, () => Array(COLS).fill(T_EMPTY));
  const data = CLASSIC_LEVELS[n - 1];
  for (let gy = 0; gy < 13; gy++) for (let gx = 0; gx < 13; gx++) {
    const t = charToTerrain(data[gy][gx]);
    if (!t) continue;
    for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++)
      map[gy * 2 + dy][gx * 2 + dx] = t;
  }
  setupSpawnsAndBase();
}

/* 加载自定义关卡（customRows 为 13x13 字符阵，由编辑器 / 分享码提供） */
function loadCustomMap() {
  map = Array.from({length: ROWS}, () => Array(COLS).fill(T_EMPTY));
  for (let gy = 0; gy < 13; gy++) for (let gx = 0; gx < 13; gx++) {
    const t = charToTerrain((customRows[gy] || ".............")[gx] || ".");
    if (!t) continue;
    for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++)
      map[gy * 2 + dy][gx * 2 + dx] = t;
  }
  setupSpawnsAndBase();
}

/* 基地围墙设为钢（铁锹道具）或恢复为砖 */
function setBaseWall(steel) {
  [[11,23],[12,23],[13,23],[14,23],[11,24],[14,24],[11,25],[14,25]].forEach(([x,y]) => {
    if (map[y][x] !== T_BASE) map[y][x] = steel ? T_STEEL : T_BRICK;
  });
}

function genMap() {
  map = Array.from({length: ROWS}, () => Array(COLS).fill(T_EMPTY));
  const rnd = Math.random;
  // 砖块列阵（经典风格：4 格间隔的 2xN 砖柱）
  for (let c = 0; c < 5; c++) {
    const bx = 4 + c * 4, by = 2 + Math.floor(rnd() * 3), bh = 8 + Math.floor(rnd() * 4);
    for (let y = by; y < by + bh && y < 22; y++) {
      map[y][bx] = T_BRICK; map[y][bx + 1] = T_BRICK;
    }
  }
  // 钢块点缀
  for (let i = 0; i < 4; i++) {
    const x = 2 + Math.floor(rnd() * 22), y = 2 + Math.floor(rnd() * 12);
    map[y][x] = T_STEEL; map[y][x+1] = T_STEEL;
  }
  // 水塘
  if (rnd() < 0.7) {
    const wx = 8 + Math.floor(rnd() * 12), wy = 10 + Math.floor(rnd() * 6);
    for (let y = wy; y < wy + 2; y++) for (let x = wx; x < wx + 4; x++)
      if (y < 22) map[y][x] = T_WATER;
  }
  // 草丛
  for (let i = 0; i < 2; i++) {
    const tx = Math.floor(rnd() * 22), ty = 4 + Math.floor(rnd() * 14);
    for (let y = ty; y < ty + 3; y++) for (let x = tx; x < tx + 3; x++)
      if (y < 22 && map[y][x] === T_EMPTY) map[y][x] = T_TREE;
  }
  // 冰面
  if (rnd() < 0.5) {
    const ix = Math.floor(rnd() * 20), iy = 6 + Math.floor(rnd() * 10);
    for (let y = iy; y < iy + 2; y++) for (let x = ix; x < ix + 3; x++)
      if (y < 22 && map[y][x] === T_EMPTY) map[y][x] = T_ICE;
  }
  setupSpawnsAndBase();
}
